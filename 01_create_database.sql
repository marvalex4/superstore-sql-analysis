-- Description: Creates and populates the superstore sales
--              database used for business intelligence analysis
-- ============================================================

-- Drop tables if they exist (safe re-run)
DROP TABLE IF EXISTS order_items;
DROP TABLE IF EXISTS orders;
DROP TABLE IF EXISTS customers;
DROP TABLE IF EXISTS products;

-- ============================================================
-- TABLE 1: CUSTOMERS
-- ============================================================
CREATE TABLE customers (
    customer_id     TEXT PRIMARY KEY,
    customer_name   TEXT NOT NULL,
    segment         TEXT NOT NULL,   -- Consumer, Corporate, Home Office
    city            TEXT NOT NULL,
    state           TEXT NOT NULL,
    region          TEXT NOT NULL    -- East, West, Central, South
);

-- ============================================================
-- TABLE 2: PRODUCTS
-- ============================================================
CREATE TABLE products (
    product_id      TEXT PRIMARY KEY,
    product_name    TEXT NOT NULL,
    category        TEXT NOT NULL,   -- Furniture, Office Supplies, Technology
    sub_category    TEXT NOT NULL
);

-- ============================================================
-- TABLE 3: ORDERS
-- ============================================================
CREATE TABLE orders (
    order_id        TEXT PRIMARY KEY,
    order_date      DATE NOT NULL,
    ship_date       DATE NOT NULL,
    ship_mode       TEXT NOT NULL,   -- First Class, Second Class, Standard Class, Same Day
    customer_id     TEXT NOT NULL REFERENCES customers(customer_id)
);

-- ============================================================
-- TABLE 4: ORDER ITEMS (fact table)
-- ============================================================
CREATE TABLE order_items (
    item_id         INTEGER PRIMARY KEY AUTOINCREMENT,
    order_id        TEXT NOT NULL REFERENCES orders(order_id),
    product_id      TEXT NOT NULL REFERENCES products(product_id),
    sales           REAL NOT NULL,
    quantity        INTEGER NOT NULL,
    discount        REAL NOT NULL DEFAULT 0,
    profit          REAL NOT NULL
);


